import { expect, it } from "vitest";
import en from "../en.json";
import ru from "../ru.json";
import uk from "../uk.json";
it.each(Object.entries({ en, ru, uk }))("keeps pricing and policy truthful in %s", (_locale, copy) => {
  const pricing = copy.home.pricing;
  const modal = copy.settings.subscription.pricing;
  expect(pricing.freeFeature1).toContain("25");
  expect(pricing.freeFeature4).toContain("2");
  expect(pricing.freeFeature6).toContain("30");
  expect(pricing.freeFeature7).toContain("1");
  expect(pricing.proFeature1).toContain("100");
  expect(pricing.proFeature6).toContain("500");
  expect(pricing.proFeature7).toContain("10");
  expect(modal.proPrice).toContain("24");
  expect(modal.freeAI).toBe(pricing.freeFeature6);
  expect(modal.proAI).toBe(pricing.proFeature6);
  expect(modal.proCoverLetters).toBe(pricing.proFeature7);
  expect(JSON.stringify(pricing)).not.toMatch(/unlimited|безлимитн|безлімітн/i);
  expect(copy.home.faq.items.free.a).toContain("30");
  expect(copy.home.faq.items.free.a).toContain("500");
  expect(copy.home.faq.items.free.a).toContain("24");
  expect(copy.home.faq.items.free.a).not.toContain("Enterprise");
  expect(copy.credits.chargePolicy).toBeTruthy();
  expect(copy.credits.allowance).toBeTruthy();
  expect(copy.credits.freePeriod).toBeTruthy();
  expect(copy.credits.proPeriod).toBeTruthy();
});
